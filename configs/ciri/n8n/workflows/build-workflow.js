#!/usr/bin/env node
// build-workflow.js — emit workflows/hdfc-sms-to-sure.json from parser/hdfc.js.
//
// The parser lives in ONE place (parser/hdfc.js, tested by run-fixtures.js).
// This script pastes it into the "Parse HDFC SMS" Code node together with the
// n8n glue below, so the workflow file never drifts from the tested code.
// Re-run after any parser change, then re-import the JSON in n8n (Workflows
// -> Import from File; overwrite the existing one).
//
//   node workflows/build-workflow.js
//   docker run --rm -v "$PWD:/w" -w /w node:22-alpine node workflows/build-workflow.js
//
// No credentials, ids, hosts or account numbers are embedded: everything
// environment-specific is read from $env at run time (see .env.example),
// and the two credentials (IMAP, Sure header auth) are attached in the UI.

'use strict';

const fs = require('fs');
const path = require('path');

const here = __dirname;
const parserSrc = fs.readFileSync(path.join(here, '..', 'parser', 'hdfc.js'), 'utf8');

// ---- Code node bodies ------------------------------------------------------

const PARSE_GLUE = `
// ---- n8n glue (generated by workflows/build-workflow.js) -------------------
const crypto = require('crypto');
const sha256 = (s) => crypto.createHash('sha256').update(s, 'utf8').digest('hex');
const ENV = {
  HDFC_SAVINGS_LAST4: $env.HDFC_SAVINGS_LAST4,
  HDFC_CC_LAST4: $env.HDFC_CC_LAST4,
  SURE_ACCOUNT_ID_SAVINGS: $env.SURE_ACCOUNT_ID_SAVINGS,
  SURE_ACCOUNT_ID_CC: $env.SURE_ACCOUNT_ID_CC,
  SURE_TAG_ID_AUTO_SMS: $env.SURE_TAG_ID_AUTO_SMS || '',
};

// The relay mail: subject "HDFC-SMS", body = the SMS as the Shortcut sent it.
// Prefer text/plain; fall back to a tag-stripped HTML body (Mail.app sends
// both). The Message trigger hands the Shortcut only the text, so nothing
// else is expected in the body.
function bodyOf(j) {
  let t = j.textPlain || '';
  if (!t && j.textHtml) {
    t = String(j.textHtml).replace(/<br\\s*\\/?>/gi, '\\n').replace(/<\\/p>/gi, '\\n')
      .replace(/<[^>]+>/g, '').replace(/&nbsp;/g, ' ').replace(/&amp;/g, '&');
  }
  return t.trim();
}

const out = [];
for (const item of $input.all()) {
  const j = item.json || {};
  const sms = bodyOf(j);
  // Fallback date (only used when the SMS itself carries none): the mail's
  // Date header, shifted to IST before taking the calendar day — an alert
  // at 01:00 IST is 19:30 UTC the previous day.
  const received = (j.date ? new Date(j.date) : new Date());
  const receivedAt = isNaN(received) ? null
    : new Date(received.getTime() + 5.5 * 3600 * 1000).toISOString().slice(0, 10);
  const res = parseSms(sms, { receivedAt, hash: sha256 });
  const rec = {
    status: res.status,
    reason: res.reason || null,
    sms,
    subject: j.subject || null,
    receivedAt,
    txn: res.txn || null,
    sure: null,
  };
  if (res.status === 'ok') {
    const s = toSure(res.txn, ENV);
    if (s.ok) rec.sure = s.body; else { rec.status = 'reject'; rec.reason = s.reason; }
  }
  out.push({ json: rec });
}
return out;
`;

const PARSE_CODE = parserSrc
  .replace(/^const api = \{[\s\S]*$/m, '') // drop the module.exports tail
  + PARSE_GLUE;

// After the Ollama call: validate the model's JSON against the SMS text
// before trusting it. Anything that fails goes to review, never to Sure.
const LLM_VALIDATE_CODE = `
// Runs once per item so $('Parse HDFC SMS').item resolves through n8n's
// paired-item tracking to the exact record this Ollama reply belongs to.
const crypto = require('crypto');
const sha256 = (s) => crypto.createHash('sha256').update(s, 'utf8').digest('hex');
const ENV = {
  HDFC_SAVINGS_LAST4: $env.HDFC_SAVINGS_LAST4,
  HDFC_CC_LAST4: $env.HDFC_CC_LAST4,
  SURE_ACCOUNT_ID_SAVINGS: $env.SURE_ACCOUNT_ID_SAVINGS,
  SURE_ACCOUNT_ID_CC: $env.SURE_ACCOUNT_ID_CC,
  SURE_TAG_ID_AUTO_SMS: $env.SURE_TAG_ID_AUTO_SMS || '',
};
const src = $('Parse HDFC SMS').item.json;
const sms = src.sms || '';
let llm = null;
try {
  const content = $json.message && $json.message.content;
  llm = typeof content === 'string' ? JSON.parse(content) : content;
} catch (e) { llm = null; }
const fail = (why) => ({ json: { ...src, status: 'reject', reason: 'llm:' + why, llm } });

if (!llm || typeof llm !== 'object') return fail('no-json');
if (llm.is_transaction !== true) return { json: { ...src, status: 'skip', reason: 'llm:not-a-transaction', llm } };
const amount = Number(llm.amount);
if (!Number.isFinite(amount) || amount <= 0) return fail('bad-amount');
// The amount must literally appear in the SMS (with or without separators).
const digits = sms.replace(/,/g, '');
const a1 = amount.toFixed(2), a2 = String(amount), a0 = String(Math.trunc(amount));
if (!(digits.includes(a1) || digits.includes(a2) || digits.includes(a0 + '.') || digits.includes(a0 + ' '))) return fail('amount-not-in-text');
if (!['debit', 'credit'].includes(llm.kind)) return fail('bad-kind');
const last4 = String(llm.account_last4 || '');
if (!/^\\d{4}$/.test(last4) || !sms.includes(last4)) return fail('last4-not-in-text');
const date = /^\\d{4}-\\d{2}-\\d{2}$/.test(llm.date || '') ? llm.date : src.receivedAt;
if (!date) return fail('no-date');
const ref = llm.reference && sms.includes(String(llm.reference)) ? String(llm.reference) : null;
const norm = sms.replace(/\\s+/g, ' ').trim();
const txn = {
  template: 'llm', kind: llm.kind, amount, currency: 'INR', date, last4,
  instrument: llm.instrument === 'card' ? 'card' : 'account',
  channel: llm.channel || 'other',
  counterparty: (llm.counterparty || '').toString().slice(0, 120) || null,
  ref, raw: sms,
  externalId: ref ? 'ref:' + ref : 'sha:' + sha256(norm).slice(0, 40),
};
const s = toSure(txn, ENV);
if (!s.ok) return fail(s.reason);
return { json: { ...src, status: 'ok', reason: 'llm', txn, sure: s.body, llm } };
`;

// toSure is needed in the validator too; take it from the parser source.
const toSureSrc = parserSrc.slice(parserSrc.indexOf('function toSure('), parserSrc.indexOf('const api = {'));
const LLM_VALIDATE_FULL = `'use strict';\n${toSureSrc}\n${LLM_VALIDATE_CODE}`;

// ---- Ollama request body ---------------------------------------------------

const LLM_SCHEMA = {
  type: 'object',
  properties: {
    is_transaction: { type: 'boolean' },
    kind: { type: 'string', enum: ['debit', 'credit'] },
    amount: { type: 'number' },
    date: { type: 'string', description: 'YYYY-MM-DD, or empty if the SMS has no date' },
    account_last4: { type: 'string', description: 'last 4 digits of the account or card named in the SMS' },
    instrument: { type: 'string', enum: ['account', 'card'] },
    channel: { type: 'string', enum: ['upi', 'card', 'neft', 'imps', 'rtgs', 'atm', 'other'] },
    counterparty: { type: 'string' },
    reference: { type: 'string', description: 'bank reference / UPI ref / RRN if present, else empty' },
  },
  required: ['is_transaction', 'kind', 'amount', 'date', 'account_last4', 'instrument', 'channel', 'counterparty', 'reference'],
};

const LLM_SYSTEM = [
  'You extract fields from Indian bank alert SMS messages (HDFC Bank).',
  'Return ONLY JSON matching the schema. Copy amounts, digits and references',
  'exactly as they appear; never invent a value that is not in the text.',
  'is_transaction is true only for money that has actually moved (debited,',
  'credited, spent, sent, received, refunded, withdrawn). OTPs, reminders,',
  'mandates, offers, failed or declined transactions are NOT transactions.',
  'Dates in the SMS are day-first (dd/mm/yy or dd-mm-yy) unless written yyyy-mm-dd.',
].join(' ');

const ollamaBody = `={{ JSON.stringify({
  model: $env.OLLAMA_MODEL || 'qwen2.5:7b-instruct',
  stream: false,
  format: ${JSON.stringify(LLM_SCHEMA, null, 1)},
  options: { temperature: 0, num_ctx: 2048 },
  messages: [
    { role: 'system', content: ${JSON.stringify(LLM_SYSTEM)} },
    { role: 'user', content: 'SMS received on ' + ($json.receivedAt || 'unknown date') + ':\\n' + $json.sms }
  ]
}) }}`;

// n8n's expression tokenizer ends an expression at the first "}}", so the
// body above must not contain that sequence anywhere before its own closing
// one. Pretty-printing the schema keeps nested braces on separate lines.
if (ollamaBody.slice(0, -2).includes('}}')) {
  throw new Error('ollamaBody contains "}}" inside the expression — n8n would truncate it');
}

// ---- Nodes -----------------------------------------------------------------

let idn = 0;
const uid = (name) => `010-${String(++idn).padStart(2, '0')}-${name.toLowerCase().replace(/[^a-z0-9]+/g, '-')}`;

const nodes = [];
const connections = {};
function add(node) { nodes.push(node); return node.name; }
function wire(from, to, { fromIndex = 0 } = {}) {
  connections[from] = connections[from] || { main: [] };
  while (connections[from].main.length <= fromIndex) connections[from].main.push([]);
  connections[from].main[fromIndex].push({ node: to, type: 'main', index: 0 });
}

const TRIGGER = add({
  id: uid('imap'), name: 'Relay inbox (IMAP)', type: 'n8n-nodes-base.emailReadImap', typeVersion: 2,
  position: [0, 300],
  parameters: {
    mailbox: 'INBOX',
    postProcessAction: 'read',
    format: 'simple',
    options: {
      // node-imap search criteria. Only unread relay mails; the subject is
      // what the Shortcut sets, so anything else landing in this inbox is
      // ignored rather than parsed.
      customEmailConfig: '["UNSEEN", ["SUBJECT", "HDFC-SMS"]]',
      forceReconnect: 60,
    },
  },
  credentials: { imap: { id: '<SET IN UI>', name: 'relay mailbox (Gmail IMAP)' } },
});

const PARSE = add({
  id: uid('parse'), name: 'Parse HDFC SMS', type: 'n8n-nodes-base.code', typeVersion: 2,
  position: [260, 300],
  parameters: { mode: 'runOnceForAllItems', jsCode: PARSE_CODE },
});
wire(TRIGGER, PARSE);

const ROUTE = add({
  id: uid('route'), name: 'Route by status', type: 'n8n-nodes-base.switch', typeVersion: 3.2,
  position: [520, 300],
  parameters: {
    rules: {
      values: ['ok', 'unparsed', 'reject', 'skip'].map((s) => ({
        conditions: {
          options: { caseSensitive: true, leftValue: '', typeValidation: 'strict', version: 2 },
          conditions: [{ id: `cond-${s}`, leftValue: '={{ $json.status }}', rightValue: s, operator: { type: 'string', operation: 'equals' } }],
          combinator: 'and',
        },
        renameOutput: true,
        outputKey: s,
      })),
    },
    options: { fallbackOutput: 'extra' },
  },
});
wire(PARSE, ROUTE);

const SURE = add({
  id: uid('sure'), name: 'Create in Sure', type: 'n8n-nodes-base.httpRequest', typeVersion: 4.2,
  position: [820, 120],
  parameters: {
    method: 'POST',
    url: '={{ $env.SURE_URL }}/api/v1/transactions',
    authentication: 'genericCredentialType',
    genericAuthType: 'httpHeaderAuth',
    sendHeaders: true,
    headerParameters: { parameters: [{ name: 'Content-Type', value: 'application/json' }] },
    sendBody: true,
    specifyBody: 'json',
    jsonBody: '={{ JSON.stringify($json.sure) }}',
    options: { response: { response: { fullResponse: true, responseFormat: 'json' } }, timeout: 20000 },
  },
  credentials: { httpHeaderAuth: { id: '<SET IN UI>', name: 'Sure API key (X-Api-Key)' } },
  onError: 'continueErrorOutput',
});
wire(ROUTE, SURE, { fromIndex: 0 });

const OLLAMA = add({
  id: uid('ollama'), name: 'Ollama extract (fallback)', type: 'n8n-nodes-base.httpRequest', typeVersion: 4.2,
  position: [820, 360],
  parameters: {
    method: 'POST',
    url: '={{ $env.OLLAMA_URL }}/api/chat',
    sendHeaders: true,
    headerParameters: { parameters: [{ name: 'Content-Type', value: 'application/json' }] },
    sendBody: true,
    specifyBody: 'json',
    jsonBody: ollamaBody,
    options: { timeout: 180000 },
  },
  onError: 'continueErrorOutput',
});
wire(ROUTE, OLLAMA, { fromIndex: 1 });

const VALIDATE = add({
  id: uid('validate'), name: 'Validate LLM output', type: 'n8n-nodes-base.code', typeVersion: 2,
  position: [1080, 360],
  parameters: { mode: 'runOnceForEachItem', jsCode: LLM_VALIDATE_FULL },
});
wire(OLLAMA, VALIDATE, { fromIndex: 0 });

const ROUTE2 = add({
  id: uid('route2'), name: 'LLM result ok?', type: 'n8n-nodes-base.if', typeVersion: 2.2,
  position: [1320, 360],
  parameters: {
    conditions: {
      options: { caseSensitive: true, leftValue: '', typeValidation: 'strict', version: 2 },
      conditions: [{ id: 'llm-ok', leftValue: '={{ $json.status }}', rightValue: 'ok', operator: { type: 'string', operation: 'equals' } }],
      combinator: 'and',
    },
    options: {},
  },
});
wire(VALIDATE, ROUTE2);
wire(ROUTE2, SURE, { fromIndex: 0 });

const NTFY = add({
  id: uid('ntfy'), name: 'ntfy: needs review', type: 'n8n-nodes-base.httpRequest', typeVersion: 4.2,
  position: [1600, 560],
  parameters: {
    method: 'POST',
    url: '=https://ntfy.sh/{{ $env.NTFY_TOPIC }}',
    sendHeaders: true,
    headerParameters: {
      parameters: [
        { name: 'Title', value: '=HDFC SMS needs review ({{ $json.status }}: {{ $json.reason || "" }})' },
        { name: 'Tags', value: 'bank,warning' },
        { name: 'Priority', value: '3' },
      ],
    },
    sendBody: true,
    specifyBody: 'string',
    body: '={{ ($json.sms || $json.message || JSON.stringify($json)).toString().slice(0, 900) }}',
    options: { timeout: 15000 },
  },
});
wire(ROUTE, NTFY, { fromIndex: 2 });       // reject
wire(ROUTE, NTFY, { fromIndex: 4 });       // fallback output (unknown status)
wire(ROUTE2, NTFY, { fromIndex: 1 });      // LLM path failed validation / skipped
wire(OLLAMA, NTFY, { fromIndex: 1 });      // Ollama HTTP error
wire(SURE, NTFY, { fromIndex: 1 });        // Sure HTTP error (4xx/5xx)

const SKIP = add({
  id: uid('skip'), name: 'Skip (not a transaction)', type: 'n8n-nodes-base.noOp', typeVersion: 1,
  position: [820, 600], parameters: {},
});
wire(ROUTE, SKIP, { fromIndex: 3 });

const KUMA_IF = add({
  id: uid('kuma-if'), name: 'Kuma push configured?', type: 'n8n-nodes-base.if', typeVersion: 2.2,
  position: [1080, 120],
  parameters: {
    conditions: {
      options: { caseSensitive: true, leftValue: '', typeValidation: 'strict', version: 2 },
      conditions: [{ id: 'kuma-set', leftValue: '={{ $env.KUMA_PUSH_URL || "" }}', rightValue: '', operator: { type: 'string', operation: 'notEmpty', singleValue: true } }],
      combinator: 'and',
    },
    options: {},
  },
});
wire(SURE, KUMA_IF, { fromIndex: 0 });

const KUMA = add({
  id: uid('kuma'), name: 'Kuma push (heartbeat)', type: 'n8n-nodes-base.httpRequest', typeVersion: 4.2,
  position: [1320, 120],
  parameters: {
    method: 'GET',
    url: '={{ $env.KUMA_PUSH_URL }}',
    sendQuery: true,
    queryParameters: {
      parameters: [
        { name: 'status', value: 'up' },
        { name: 'msg', value: '=sure {{ $json.statusCode }} {{ $json.body && $json.body.id ? $json.body.id : "" }}' },
      ],
    },
    options: { timeout: 10000 },
  },
  onError: 'continueRegularOutput',   // a lost heartbeat must not fail the run
});
wire(KUMA_IF, KUMA, { fromIndex: 0 });

// ---- Workflow --------------------------------------------------------------

const workflow = {
  name: 'HDFC SMS -> Sure (proposal 010)',
  nodes,
  connections,
  settings: {
    executionOrder: 'v1',
    timezone: 'Asia/Kolkata',
    saveExecutionProgress: false,
    saveManualExecutions: true,
    saveDataSuccessExecution: 'all',
    saveDataErrorExecution: 'all',
  },
  meta: { generatedBy: 'configs/ciri/n8n/workflows/build-workflow.js', instanceId: '<n8n instance>' },
};

const outFile = path.join(here, 'hdfc-sms-to-sure.json');
fs.writeFileSync(outFile, JSON.stringify(workflow, null, 2) + '\n');
console.log(`wrote ${path.relative(process.cwd(), outFile)} (${nodes.length} nodes)`);
